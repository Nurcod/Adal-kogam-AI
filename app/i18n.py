def detect_lang(text: str) -> str:
    if any(ch in KK_LETTERS for ch in text):
        return "kk"
    words = set(re.findall(r"\w+", text.lower()))
    if words & KK_WORDS:
        return "kk"
    if re.search(r"[а-яё]", text.lower()):
        return "ru"
    if re.search(r"[a-z]", text.lower()):
        return "en"
    return "ru"



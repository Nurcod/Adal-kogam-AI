def random_question(exclude: set | None = None) -> dict:
    pool = [q for q in _QUIZ if q["id"] not in (exclude or set())] or _QUIZ
    return random.choice(pool)


def get(qid: str) -> dict | None:
    return next((q for q in _QUIZ if q["id"] == qid), None)


def total() -> int:
    return len(_QUIZ)

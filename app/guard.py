"""Предварительная проверка запроса до обращения к модели (быстро и бесплатно):
пустые/слишком длинные сообщения, приветствия, попытки «взломать» инструкции бота."""
import re

INJECTION_PATTERNS = [
    r"ignore (all |the )?(previous|above|prior) (instructions|prompts?)",
    r"system prompt", r"jailbreak", r"\bDAN\b", r"developer mode",
    r"игнорир\w*\s+(?:\w+\s+){0,3}(инструкц|правил|указан|промпт)",
    r"забудь\s+(?:\w+\s+){0,3}(инструкц|правил)", r"системн\w+ (промпт|инструкц)",
    r"ты теперь (не )?\w+ бот", r"притворись", r"представь, что ты",
    r"нұсқаулықт\w* елеме",
]
GREETINGS = {"привет", "здравствуйте", "салам", "сәлем", "сәлеметсіз бе", "салем", "hello", "hi",
             "салеметсиз бе", "салеметсызбе", "сәлеметсіз", "хай", "здарова", "ку",
             "добрый день", "қайырлы күн", "ассалаумағалейкум", "ассаламуалейкум"}

MAX_LEN = 1500

# Бытовые фразы: отвечаем дружелюбно и сразу, без обращения к модели
SMALLTALK = [
    ("help", r"(^/?help$|команд|помощь|помоги(те)?\s*(мне)?\s*(с\s+бот|с\s+команд|разобраться|пользоваться)?\s*[?!.]*$"
             r"|что ты (умеешь|можешь)|как (тобой )?пользоваться|как работает(шь)? (бот|ты)|с чего начать"
             r"|кто ты|ты кто|что ты такое|көмек|не істей аласы|қалай қолдан|командалар|сен кімсің)"),
    ("thanks_reply", r"^(большое |огромное )?(спасибо|благодарю|спс|рахмет|көп рахмет|thanks|thank you)\b"),
    ("smalltalk", r"^(как (ты|дела|жизнь|поживаешь|сам)|че как|қалайсың|қалың қалай|хал-жағдай|"
                  r"жағдайың қалай|калайсы\w*|кал калай|жагдай калай)\b"),
    ("smalltalk", r"^(?:(?:ага|угу|понятно|ясно|интересно|ок|окей|ok|хорошо|класс|круто|супер|отлично|"
                  r"вау|ого|түсінікті|жақсы|керемет|пока|до свидания|сау бол|сау болыңыз)[\s,!.)?]*)+$"),
]


def precheck(text: str) -> str | None:
    """Возвращает код проблемы или None, если запрос можно обрабатывать."""
    clean = (text or "").strip()
    if not re.search(r"\w", clean):
        return "empty"
    if len(clean) > MAX_LEN:
        return "too_long"
    low = clean.lower()
    if any(re.search(p, low, re.IGNORECASE) for p in INJECTION_PATTERNS):
        return "injection"
    if low.strip("!.?, ") in GREETINGS:
        return "greeting"
    if len(low) <= 80:  # длинный вопрос по существу не считаем бытовой фразой
        for code, pattern in SMALLTALK:
            if re.search(pattern, low):
                return code
    return None

def build_context(hits) -> str:
    parts = []
    for n, h in enumerate(hits, 1):
        c = h.chunk
        head = f"[{n}] Документ: {c.title}"
        if c.label:
            head += f" — {c.label}"
        if c.in_constitution:
            head += f"\nЗакреплено в Конституции РК 2026: {c.in_constitution}"
        if c.sources:
            head += f"\nИсточник: {c.sources[0].name}"
        parts.append(f"{head}\n{c.text}")
    return "\n\n---\n\n".join(parts)

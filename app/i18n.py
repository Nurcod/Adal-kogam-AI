"""Определение языка и тексты интерфейса на казахском и русском."""
import re

KK_LETTERS = set("әғқңөұүһіӘҒҚҢӨҰҮҺІ")
# «не» сюда не входит: по-русски это частица отрицания («если я не уступлю…»)
KK_WORDS = {"және", "қалай", "деген", "туралы", "бойынша", "қандай", "ма", "ме", "бе", "па",
            "сәлем", "сәлеметсіз", "рахмет", "конституциясы", "бап", "заң", "мемлекет", "дегеніміз"}


def detect_lang(text: str) -> str:
    if any(ch in KK_LETTERS for ch in text):
        return "kk"
    words = set(re.findall(r"\w+", text.lower()))
    if words & KK_WORDS:
        return "kk"
    if re.search(r"[а-яё]", text.lower()):
        return "ru"
    if re.search(r"[a-z]", text.lower()):
        return "en"
    return "ru"


